export function generateInitialStock() {
  const stock = [];
  const branches = ['B1', 'B2', 'B3', 'B4'];

  INITIAL_PRODUCTS.forEach(p => {
    branches.forEach((b, idx) => {
      // Branch 1 (Rajahmandary Main Branch) has full stock, others have varied realistic quantities
      let qty = p.price > 10000 ? 3 : 18;
      if (b === 'B2') qty = p.price > 10000 ? 2 : 12;
      if (b === 'B3') qty = p.price > 10000 ? 1 : 8;
      if (b === 'B4') qty = p.price > 10000 ? 0 : 4; // B4 has low stock on some items

      stock.push({
        id: `${b}__${p.id}`,
        branch: b,
        productId: p.id,
        qty,
        damaged: p.id === 'p_0005' && b === 'B1' ? 1 : 0,
        min: p.price > 10000 ? 1 : 5,
        inTransit: p.id === 'p_0009' && b === 'B2' ? 2 : 0,
      });
    });
  });

  return stock;
}

